"""The pinned Graphviz version, and the two readings that are held to it.

WHY THIS EXISTS. Graphviz stamps its own version into every SVG it renders, as
the comment line ``<!-- Generated by graphviz version X (build) -->``. So
regenerating a tracked SVG on a machine whose Graphviz differs from the one that
last rendered it rewrites that line, in every file regenerated, as a side effect
of whatever change was actually intended. That is not hypothetical here: on
2026-09-09 MAM-private's ``3f53991`` regenerated al-hatorah's pipeline graph for
a deliberate node-label change and carried the stamp from 15.1.1 to 16.0.0 with
it, unremarked. A survey that day found three different Graphviz versions already
committed across this repo and MAM-private -- so the drift had happened twice
before anyone looked.

Ben's decision, 2026-09-09: accept 16.0.0 as the first pinned version, and make
the pin BIDIRECTIONAL -- an older Graphviz must fail exactly as loudly as a newer
one, since either rewrites the line.

WHAT IS PINNED IS THE FULL STAMP, NOT THE VERSION NUMBER, and that is the whole
point rather than an over-tightening. The guarantee wanted is "regenerating
cannot change this line", and the line carries the build date too. A same-version
Graphviz built on a different date -- another machine, another installer -- would
rewrite the build half of the stamp in every tracked SVG while a version-only pin
sat green. Ben chose the full stamp, 2026-09-09, knowing it means a benign rebuild
trips the check; when it does, the answer is to look at whether the tracked files
really would change, and then either match the build or raise the pin.

TWO READINGS, AND NEITHER ONE COVERS THE OTHER'S GROUND.

  * ``check_installed`` asks the dot executable what it is, and refuses to render
    with the wrong one. This is what PREVENTS a mis-stamped file being written,
    and it fires at the moment of rendering, where the error can say what to do.
    It reaches only files some generator actually renders.
  * ``stamp_in_svg_text`` reads the stamp back out of a file that already exists,
    for ``py/tests/test_graphviz_version_pin.py`` to hold every tracked SVG to
    the pin. This is what catches a file no generator owns, and a file committed
    from a machine that skipped the check. It needs no Graphviz installed, so it
    runs in a container that has none.
    ``doc/process-documentation/MAM-process.dot.svg`` was the worked example of
    the first kind and is no longer: ``py/main_pipeline_graph.py`` renders it as
    of 2026-09-09, so ``check_installed`` reaches it too. The reading stays for
    the next unowned file, whenever one arrives.

A MISSING GRAPHVIZ IN THE CLOUD IS A SKIP, AND EVERYWHERE ELSE IS FATAL. Ben's
decision, 2026-09-09, and the reason is ``py/main_0_mega.py``: its ``tmpl-survey``
step is step 5 of 41, and it reaches ``survey_dot.render_svg``. When a missing
Graphviz raised unconditionally, a cloud container ran four steps and then died,
and the remaining 36 -- the whole accgram block, ``mam-simple``, ``mam-osis``,
``near-aleppo-census``, ``gen-site`` -- never ran at all. That is far too high a
price for an artifact a container cannot produce anyway. So ``in_cloud_session``
gates the choice: in a container the render is skipped, recorded by
``note_cloud_skip`` and reported once at the end of the mega run; anywhere else
it raises, exactly as before.

A skipped run is CLOUD-COMPLETE, which means no step failed and every step either
ran or was skipped for the cloud, while some SVGs went unrendered. It is
deliberately not called incomplete -- Ben's wording, 2026-09-09. Since 2026-09-10
the mega also skips two whole steps in a cloud session, the near-Aleppo census
and the post-stress-meteg survey, and ``py/main_0_mega.py``'s
``_report_cloud_skips`` reports both kinds of skip. The one hazard an SVG skip
leaves is that the ``.dot`` beside a skipped ``.svg`` IS rewritten, so the
tracked pair can drift apart; the mega's end-of-run banner says so, and says not
to commit a changed ``.dot`` without its ``.svg``.

PIP CANNOT SUPPLY GRAPHVIZ, AND THAT WAS CHECKED RATHER THAN ASSUMED. Ben asked
on 2026-09-09 whether a pip install could provide it, which would be a better
design than this one: a pinned entry in ``requirements.txt`` would make the
version reproducible on every machine and container automatically, satisfying the
pin BY CONSTRUCTION instead of by a rule people must follow. As of that date no
package delivers it, measured against PyPI rather than recalled:

  * ``graphviz`` is a 38-file pure-Python wrapper, 138 KB unpacked, with zero
    executables. It shells out to a ``dot`` you must already have. The name
    invites the opposite conclusion, which is why this bullet is first.
  * ``pygraphviz`` bundles the Graphviz libraries and eight auxiliary tools, but
    ``dot`` is NOT among them; it lays out through the C library. Adopting it
    would mean rewriting every generator away from ``subprocess``.
  * ``graphviz-static`` genuinely does ship static ``dot`` binaries for every
    platform -- and still is not the answer. It bundles Graphviz 14.1.1, two
    majors behind this pin, so adopting it would drag all 16 tracked SVGs
    backwards; and all eight of its releases landed inside a three-day window in
    December 2025 with nothing since, while Graphviz shipped 15.x and 16.x.

Do not re-derive this. The non-pip routes that do work are the OS package manager
in a container image and conda-forge, and both pin to whatever that channel
ships. If a maintained binary-shipping wheel ever appears it is worth revisiting,
because a pinned dependency beats a pinned constant.

RAISING THE PIN IS ONE EDIT HERE, then a regeneration of every tracked SVG,
committed on its own rather than riding along with unrelated work -- the same
discipline ``~/.claude/CLAUDE.md`` states for a black version bump, and for the
same reason: a regeneration that rides along makes a small change look like a
formatting commit. MAM-private pins the same version independently, in
``MAM-private/py/tests/test_graphviz_version_pin.py``; the two repos are
deliberately NOT wired together, since a vendoring relationship governed by
``in/vendoring_policy.json`` would cost more than the one string it kept in step.
Raising the pin means editing both.
"""

import os
import re
import subprocess
import sys

# The Graphviz that every tracked SVG in this repo was rendered by. Raising this
# is a deliberate act; see this module's docstring for what else it obliges.
PINNED_STAMP = "16.0.0 (20260814.1018)"

# Ben's decision, 2026-09-09: a missing Graphviz is FATAL on his own machines and
# a recorded SKIP in a cloud container -- see this module's docstring, section
# "A MISSING GRAPHVIZ IN THE CLOUD IS A SKIP".
#
# CLAUDE_CODE_REMOTE is an EXISTING variable, not one invented for this, and it
# is the discriminator this repository already relies on: .claude/hooks/
# install-user-config.sh gates on it so that it never touches ~/.claude/ on Ben's
# own machines, and doc/user-level-config-in-cloud-sessions.md calls it "the
# documented discriminator: the cloud VM sets it and it is never true locally",
# measured in a container on 2026-09-09. Verified unset in a local session the
# same day. Platform is deliberately NOT used as a proxy -- Ben's instruction was
# explicit that "not Windows" must not stand in for "cloud", and it would be
# wrong in both directions: a Linux machine of his is not a container, and a
# container could be any platform.
_CLOUD_ENV_VAR = "CLAUDE_CODE_REMOTE"

# Every SVG this process decided not to render, in order. Read by main_0_mega.py
# so that one run reports its skips once at the end rather than only in the
# scroll-back beside whichever step produced them.
_CLOUD_SKIPPED_RENDERS = []


def in_cloud_session():
    """True when running in a Claude Code cloud container."""
    return os.environ.get(_CLOUD_ENV_VAR) == "true"


def note_cloud_skip(svg_path):
    """Record and announce one SVG left unrendered for want of Graphviz."""
    _CLOUD_SKIPPED_RENDERS.append(svg_path)
    print(
        f"SVG NOT RENDERED, no Graphviz in this cloud container: {svg_path}",
        file=sys.stderr,
    )


def cloud_skipped_renders():
    """The SVGs skipped so far in this process, oldest first."""
    return tuple(_CLOUD_SKIPPED_RENDERS)


# The stamp as it appears in a rendered SVG. Graphviz breaks the comment across
# two lines -- the closing "-->" sits on the next line -- so the pattern stops at
# the closing parenthesis of the build rather than looking for the comment's end.
_SVG_STAMP_RE = re.compile(r"<!--\s*Generated by graphviz version (\S+ \([^)]*\))")

# The stamp as `dot -V` reports it: "dot - graphviz version 16.0.0 (20260814.1018)".
_DOT_VERSION_RE = re.compile(r"graphviz version (\S+ \([^)]*\))")


def stamp_in_svg_text(svg_text):
    """Return the Graphviz stamp in `svg_text`, or None if it carries none.

    None means "not Graphviz output" far more often than it means "damaged": this
    repo tracks one hand-made SVG exported from a Google Drawing. The lint names
    that file rather than trusting the absence, so that a Graphviz SVG which lost
    its stamp cannot pass by looking like the hand-made one.
    """
    match = _SVG_STAMP_RE.search(svg_text)
    return match.group(1) if match else None


def installed_stamp(dot_exe):
    """Return the stamp `dot -V` reports for `dot_exe`.

    Graphviz has printed its version banner to stderr in some releases and to
    stdout in others, so both are searched rather than guessing which.
    """
    completed = subprocess.run(
        [dot_exe, "-V"],
        capture_output=True,
        check=True,
        encoding="utf-8",
    )
    banner = (completed.stderr or "") + (completed.stdout or "")
    match = _DOT_VERSION_RE.search(banner)
    if match is None:
        raise ValueError(
            f"Could not read a Graphviz version from {dot_exe!r}; "
            f"`dot -V` said: {banner!r}"
        )
    return match.group(1)


def check_installed(dot_exe):
    """Raise unless `dot_exe` is the pinned Graphviz. Returns the stamp on success."""
    found = installed_stamp(dot_exe)
    if found != PINNED_STAMP:
        raise RuntimeError(
            f"Graphviz version mismatch: this repo pins {PINNED_STAMP}, but "
            f"{dot_exe} is {found}. Every tracked SVG here carries the pinned "
            "stamp, so rendering with a different Graphviz would rewrite that "
            "line in each file it touches. Either install the pinned version, "
            "or -- if this bump is deliberate -- raise PINNED_STAMP in "
            "py/mb_cmn/graphviz_pin.py, regenerate every tracked SVG, and commit "
            "that regeneration on its own."
        )
    return found
