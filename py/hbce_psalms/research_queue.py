"""Build the research queue, ``out/research_queue.md``, from ``out/candidates_with_ML_UXLC.tsv``.

Each row gets the Aleppo location implied by HBCE's line-break markup, and the mgketer, MwD,
tica and UXLC links that ``py/main_verse_links.py`` prints, taken from the two functions it
takes them from: ``mb_cmn.verse_external_links.verse_links`` and
``hkq_cmn.uxlc_external_links.verse_links``. No link is assembled here.

Every form in the queue is shown in MAM-normal mark order, as every tracked ``.md`` in this
repository must be (``py/tests/test_prose_mark_order.py``); the TSVs keep each source's order.
"""

import json
import re
import xml.etree.ElementTree as ET
from collections import defaultdict

from hbce_psalms import hbce_paths
from hbce_psalms.candidates import load, real_labels
from hbce_psalms.compare import TEI_NS, skeleton
from hkq_cmn import uxlc_external_links
from mb_cmn import hebrew_punctuation as hpu
from mb_cmn import verse_external_links as vel
from mb_cmn.uni_denorm import give_std_mark_order

SHOWN_PASEQ = " " + hpu.PASOLEG
_VEL_LABELS = ("mgketer", "MwD", "tica")
_UXLC_LABEL = "UXLC"
_HEADER_LINES = (
    "# Research queue: HBCE's Aleppo transcription versus MAM, Psalms 1-14 and 25-51",
    "",
    "Generated by py/main_hbce_psalms.py compare from"
    " hbce-psalms/out/candidates_with_ML_UXLC.tsv,",
    "from the HBCE snapshot of 2026-09-26. Forms are lifted from the data, never retyped,",
    "and shown in MAM-normal mark order. 'Location' is the archive.org page index (n) with",
    "the column and line implied by the HBCE line-break markup; 'HBCE Leningrad' is HBCE's",
    "Leningrad transcription; 'UXLC' is the Unicode/XML Leningrad Codex. The links are the",
    "ones py/main_verse_links.py prints.",
    "",
)


def hbce_positions() -> dict:
    """(ref, skeleton) -> (archive page n, column, line) for every Aleppo chanted word."""
    meta_path = hbce_paths.metadata_dir() / "MA_meta.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    pages = meta["data"]["manuscript"]["pages"]["page"]
    folio_of = {p["pageID"]: p.get("folio") for p in pages}
    pos = {}
    for path in sorted(hbce_paths.transcriptions_dir().glob("MA_*.xml")):
        page_id = int(path.stem.split("_")[1])
        root = ET.parse(path).getroot()
        col, line, ref, pending = None, 0, None, ""
        for el in root.find(f".//{TEI_NS}body").iter():
            tag = el.tag.replace(TEI_NS, "")
            if tag == "cb":
                col, line = el.get("n"), 0
            elif tag == "lb":
                line += 1
            elif tag == "ab":
                m = re.fullmatch(r"Ps\.(\d+)\.(\d+)|B25K(\d+)V(\d+)", el.get("n") or "")
                if m:
                    c, v = (
                        (m.group(1), m.group(2))
                        if m.group(1)
                        else (m.group(3), m.group(4))
                    )
                    ref = f"Ps.{c}.{v}"
            elif tag == "w":
                text = "".join(el.itertext())
                s = skeleton(text)
                full = pending + s
                pending = full if text.endswith(hpu.MAQ) else ""
                for key in {s, full}:
                    if key:
                        pos.setdefault((ref, key), (folio_of.get(page_id), col, line))
    return pos


def verse_links(ref: str, cache: dict) -> str:
    """The mgketer, MwD, tica and UXLC links of a verse, as the queue's Links cell."""
    if ref in cache:
        return cache[ref]
    _, c, v = ref.split(".")
    chapter, verse = int(c), int(v)
    links = [
        link
        for link in vel.verse_links("Psalms", chapter, verse)
        if link.label in _VEL_LABELS
    ]
    links += [
        link
        for link in uxlc_external_links.verse_links("Psalms", chapter, verse)
        if link.label == _UXLC_LABEL
    ]
    cache[ref] = " · ".join(f"[{link.label}]({link.href})" for link in links)
    return cache[ref]


def category(labels: str) -> str:
    """The queue's heading for a row, from its labels."""
    text = " ".join(real_labels({"labels": labels}))
    if "letters" in text:
        return "letters"
    if "maqaf" in text or "missing-in" in text or "extra-in" in text:
        return "maqaf or grouping"
    if "oleh-position" in text:
        return "oleh position"
    if "stroke-shape" in text:
        return "stroke shape (meteg or silluq vs an accent)"
    if "accent:" in text:
        return "accent"
    if "dagesh" in text:
        return "dagesh or shuruq dot"
    if "hataf-without-mam-note" in text:
        return "hataf with no MAM doc-note"
    if "vowel" in text or "other:" in text or "shin-sin" in text:
        return "vowel or dot"
    if "rafe" in text:
        return "rafe (HBCE never transcribes it)"
    if "silluq" in text:
        return "silluq presence or place"
    if "meteg" in text:
        return "meteg presence or place"
    return "other"


def tier(row) -> str:
    """The queue's tier for a row: what MAM and the UXLC say about the chanted word."""
    if row["docnote"] == "word-note":
        return "C. MAM already documents the word"
    if row["HBCE-Aleppo-vs-UXLC"] == "HBCE-Aleppo == UXLC":
        return (
            "B. HBCE's Aleppo form equals the UXLC"
            " (possible base-text carry-over; no MAM note on the word)"
        )
    return (
        "A. HBCE reads Aleppo against both MAM and the UXLC (no MAM note on the word)"
    )


def write_research_queue() -> dict:
    """Write ``out/research_queue.md``; return the number of rows in each tier."""
    rows = load(hbce_paths.out_dir() / "candidates_with_ML_UXLC.tsv")
    pos = hbce_positions()
    cache = {}
    by_tier = defaultdict(lambda: defaultdict(list))
    for r in rows:
        labs = real_labels(r)
        if not labs:
            continue
        probe = r["Aleppo(HBCE)"] if r["Aleppo(HBCE)"] not in ("—", "") else r["MAM"]
        where = pos.get((r["ref"], skeleton(probe.replace(SHOWN_PASEQ, ""))))
        loc = (
            f"n{where[0]} col {where[1]} line {where[2]}" if where and where[0] else "?"
        )
        by_tier[tier(r)][category(r["labels"])].append((r, loc, "; ".join(labs)))
    lines = list(_HEADER_LINES)
    counts = {}
    for t in sorted(by_tier):
        n_t = sum(len(v) for v in by_tier[t].values())
        counts[t] = n_t
        lines += [f"## {t} ({n_t} rows)", ""]
        for cat in sorted(by_tier[t]):
            items = by_tier[t][cat]
            lines += [
                f"### {cat} ({len(items)})",
                "",
                "| Verse | MAM | HBCE Aleppo | HBCE Leningrad | UXLC | Difference"
                " | Note status | Location | Links |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
            for r, loc, labs in items:
                forms = [r["MAM"], r["Aleppo(HBCE)"], r["Leningrad(HBCE)"], r["UXLC"]]
                cells = [
                    r["ref"].replace("Ps.", "Ps ").replace(".", ":"),
                    *(give_std_mark_order(form) for form in forms),
                    labs.replace("|", "/"),
                    r["docnote"],
                    loc,
                    verse_links(r["ref"], cache),
                ]
                lines.append("| " + " | ".join(cells) + " |")
            lines.append("")
    path = hbce_paths.out_dir() / "research_queue.md"
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return counts
