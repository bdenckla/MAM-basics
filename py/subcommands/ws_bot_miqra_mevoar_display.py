"""Create or update Miqra Mevoar's display pages on Hebrew Wikisource through the bot.

Usage (run from the repository root):
    .venv/Scripts/python.exe py/main_ws_bot.py miqra-mevoar-display --no-save -dir:path/to/.pywikibot
    .venv/Scripts/python.exe py/main_ws_bot.py miqra-mevoar-display --summary "..." -dir:path/to/.pywikibot

The selected pages are those that --page names, from either of two tables of
py/miqra_mevoar/display_page.py, or every page of PAGES where --page names none; a page
of BLOCK_ONLY_PAGES is selected only by name. A page of PAGES is generated by
display_page.page_text from MAM-simple and the tracked JSON in in/miqra-mevoar/ or, for
the Torah, the places of the headings in its base chapters in
in/miqra-mevoar-base-headings/, before any page is read. A page of BLOCK_ONLY_PAGES,
one of Avi's pages for the Five Megillot, which the bot did not make, is generated from
its live text by display_page.block_only_page_text, which adds its block of title and
navigation at its top and changes no other line (Stage 15 of doc/PLAN-miqra-mevoar.md).
Each generated page is compared with the latest revision of the live page, and the page
then has one of four outcomes:
  create     the page does not exist. It is saved with createonly, so that a page someone
             else made in the meantime is not overwritten. A page of BLOCK_ONLY_PAGES
             is never created: one that does not exist is refused.
  unchanged  the live text equals the generated text. Nothing is done.
  update     the live text differs from the generated text only in a block at the top
             of either and in their category lines, as display_page.differs_only_in_block
             decides, the update rule of Stage 14 of the plan. So an update adds or
             replaces a block and may change the category's sort key, and changes
             nothing else. It is saved with nocreate, with the revision whose text was
             compared as baserevid and its time as basetimestamp, so that an edit made
             since makes MediaWiki detect a conflict.
  refuse     the page exists with another text, or a page of BLOCK_ONLY_PAGES does not
             exist or no block can be added to it: its live text does not read, its
             verse lines name another book, it begins with a block other than its own,
             or it has no heading, which leaves its block without a topic, and the block
             of such a page waits on decision 14 of the plan. Nothing is saved for it; the
             run records the reason, lists the editors of the page's revisions and
             exits non-zero when it ends. People, not the bot, reconcile such a page.

Every run writes the live text of each selected page that exists to its live/
directory, each generated page to its pages/ directory and each page's outcome, with the
reason for a refusal, the revision whose text was compared and the counts of verse
lines, breaks and headings, to misc/outcomes.json. `--no-save` also renders each
generated page through the API's parse action, which saves nothing, and requires that
no link or transcluded page on it be missing, as a misspelled book name or a missing
base chapter would make one, and that the page use no more than 90% of MediaWiki's
limit on the post-expand include size, past which the page's last templates are left
unexpanded. It records in each page's outcome the page's missing pages and its include
size: the bytes used and the limit. It saves nothing and, like the other modes' dry
runs, exits non-zero if any page would be created or updated. A saving run reads each
saved revision back through the API, uncached, requires its bytes to equal the
generated text's, records each page's old and new revision ids and its diff link in
misc/saved-pages.json, and exits non-zero on any mismatch. No MAM page changes, so
there is no post-run download. Each run's artifacts go to a fresh directory under
.novc/mam-ws-bot-miqra-mevoar-display-runs/.
"""

import dataclasses
import os
import time
from datetime import datetime

import pywikibot

from mb_cmn import file_io
from mb_cmn import polite_download
from mb_cmn.he_wikisource_url import he_diff_url
from mb_cmn.new_york_time import NEW_YORK
from mb_misc import my_utils_for_mainish as my_utils_fm
from miqra_mevoar import display_page
from subcommands import ws_bot_real
from ws import ws_revision_api


@dataclasses.dataclass(frozen=True)
class _Live:
    """A live page's latest revision: its text, which a run compares with the generated
    text, and the revision on which an update rests."""

    text: str
    revid: int
    user: str | None
    timestamp: pywikibot.Timestamp


def run(keys, pywikibot_args, summary=None, no_save=False):
    """Create or update the selected display pages, saving nothing if no_save."""
    ws_bot_real.assert_pywikibot_dir_configured(pywikibot_args)
    if not no_save and not summary:
        raise SystemExit("A saving run needs --summary")
    selected = _selected_pages(keys)
    # Every page of PAGES is generated, and its generator's checks pass, before any page
    # is read; a page of BLOCK_ONLY_PAGES is generated from its live text.
    texts = {
        entry.title(): display_page.page_text(entry)
        for entry in selected
        if not _is_block_only(entry)
    }
    run_root = os.path.join(_RUNS_ROOT, datetime.now(NEW_YORK).strftime(_STAMP))
    my_utils_fm.show_progress_g(__file__, "run-artifacts", run_root)
    site = pywikibot.Site("he", "wikisource", "BDencklaBot")
    outcomes, saved, failures = [], [], []
    try:
        for page_entry in selected:
            title = page_entry.title()
            page = pywikibot.Page(site, title)
            live = _live(page)
            if live is not None:
                _write_text_file(run_root, "live", page_entry.key, live.text)
            reason = None
            if _is_block_only(page_entry):
                text, reason = _block_only_text(page_entry, live)
                if text is not None:
                    texts[title] = text
            else:
                text = texts[title]
            if text is None:
                outcome = "refuse"
            else:
                _write_text_file(run_root, "pages", page_entry.key, text)
                outcome = _outcome(live, text)
                if outcome == "refuse":
                    reason = _ANOTHER_TEXT
            entry = {
                "key": page_entry.key,
                "title": title,
                "outcome": outcome,
                "reason": reason,
                "checked-revision": _revision_record(live),
                "revisions": (
                    _revisions(page) if outcome == "refuse" and live is not None else []
                ),
                "counts": None if text is None else _counts(_verses(page_entry, text)),
                "missing-pages": None,
                "include-size": None,
            }
            outcomes.append(entry)
            print(f"{outcome:<9} {title}")
            if no_save:
                if text is not None:
                    entry["missing-pages"], entry["include-size"] = _parse_checks(
                        site, title, text
                    )
                continue
            if outcome not in ("create", "update"):
                continue
            try:
                saved.append(_save(page, title, text, outcome, summary, live))
            except pywikibot.exceptions.Error as error:
                failures.append(f"{title}: the save failed: {error!r}")
                break
    finally:
        file_io.json_dump_to_file_path(
            outcomes, os.path.join(run_root, "misc", "outcomes.json")
        )
        saved_path = os.path.join(run_root, "misc", "saved-pages.json")
        # Preserve known saved revision IDs if verification raises.
        file_io.json_dump_to_file_path(saved, saved_path)
        if saved:
            failures.extend(_verify(saved, texts))
        file_io.json_dump_to_file_path(saved, saved_path)
    _exit_if_any(outcomes, failures, no_save)


def _selected_pages(keys):
    """The pages that --page names, in the order named, from PAGES or BLOCK_ONLY_PAGES,
    or every page of PAGES where it names none."""
    if not keys:
        return list(display_page.PAGES.values())
    if len(set(keys)) != len(keys):
        raise SystemExit(f"A --page is given twice: {keys}")
    tables = {**display_page.PAGES, **display_page.BLOCK_ONLY_PAGES}
    if unknown := sorted(set(keys) - set(tables)):
        raise SystemExit(f"No --page {unknown}; the pages are {list(tables)}")
    return [tables[key] for key in keys]


def _is_block_only(entry):
    """Whether a selected page is of BLOCK_ONLY_PAGES; False for a page of PAGES."""
    if isinstance(entry, display_page.BlockOnlyPage):
        return True
    if isinstance(entry, display_page.Page):
        return False
    raise TypeError(f"{entry!r} is a page of neither table")


def _live(page):
    """The page's latest revision, or None where the page does not exist."""
    if not page.exists():
        return None
    revision = page.latest_revision
    if revision.text is None:
        raise ValueError(f"The latest revision of {page.title()} gives no text")
    return _Live(revision.text, revision.revid, revision.user, revision.timestamp)


def _block_only_text(entry, live):
    """A page of BLOCK_ONLY_PAGES: its generated text and None, or None and the reason
    that it is refused, where the page does not exist or no block can be added to it."""
    if live is None:
        return None, "a page of BLOCK_ONLY_PAGES that does not exist"
    try:
        return display_page.block_only_page_text(entry, live.text), None
    except ValueError as error:
        return (
            None,
            f"a page of BLOCK_ONLY_PAGES to which no block can be added: {error}",
        )


def _outcome(live, text):
    """The outcome of a page whose generated text is text: create, unchanged, update or
    refuse, as the module's docstring says."""
    if live is None:
        return "create"
    if live.text == text:
        return "unchanged"
    if display_page.differs_only_in_block(live.text, text):
        return "update"
    return "refuse"


def _revision_record(live):
    """The revision whose text a run compared, or None where the page does not exist."""
    if live is None:
        return None
    return {
        "revid": live.revid,
        "user": live.user,
        "timestamp": live.timestamp.isoformat(),
    }


def _revisions(page):
    """Every revision of a refused page, with its editor and its time."""
    return [
        {
            "revid": revision.revid,
            "user": revision.user,
            "timestamp": revision.timestamp.isoformat(),
        }
        for revision in page.revisions()
    ]


def _verses(entry, text):
    """The verses of a page's generated text, as its table's reader reads them."""
    if _is_block_only(entry):
        _block_name, verses, _sort_key, _notes = display_page.read_block_only_page(text)
        return verses
    _block_name, verses, _sort_key = display_page.read_page(text)
    return verses


def _counts(verses):
    """A page's counts, in the columns of Stage 10's table in doc/PLAN-miqra-mevoar.md.

    A line of the Decalogue is a verse line, and a disputed petuha, whose break line's
    first parameter may give Avi's note beside its letter, is a petuha.
    """
    breaks = sum(verse.letter is not None for verse in verses)
    headings = sum(verse.heading is not None for verse in verses)
    both = sum(
        verse.letter is not None and verse.heading is not None for verse in verses
    )
    return {
        "verse-lines": len(verses),
        "petuhot": sum(verse.letter in display_page.PETUHA_LETTERS for verse in verses),
        "setumot": sum(verse.letter == display_page.SAMEKH for verse in verses),
        "headings": headings,
        "break-only": breaks - both,
        "heading-only": headings - both,
        "both": both,
    }


def _parse_checks(site, title, text):
    """Render text as title, saving nothing; give its missing pages and include size.

    The missing pages are the links and transcluded pages that do not exist. The include
    size is the post-expand include size that the parse's limit report gives: the bytes
    used and MediaWiki's limit on them.
    """
    parsed = site.simple_request(
        action="parse",
        title=title,
        text=text,
        contentmodel="wikitext",
        prop="links|templates|limitreportdata",
        formatversion=2,
    ).submit()["parse"]
    missing = []
    for prop in ("links", "templates"):
        for item in parsed[prop]:
            if not isinstance(item.get("exists"), bool) or "title" not in item:
                raise ValueError(f"The parse of {title} gives an unknown {prop} item")
            if not item["exists"]:
                missing.append(item["title"])
    return sorted(set(missing)), _include_size(title, parsed["limitreportdata"])


def _include_size(title, limit_report):
    """The post-expand include size in the parse's limit report: bytes used and limit."""
    items = [item for item in limit_report if item["name"] == _INCLUDE_SIZE_ITEM]
    if len(items) != 1:
        raise ValueError(
            f"The parse of {title} gives {len(items)} {_INCLUDE_SIZE_ITEM} items"
        )
    used, limit = items[0].get("0"), items[0].get("1")
    # The type, not isinstance, since a bool is an int to isinstance.
    if type(used) is not int or type(limit) is not int:
        raise ValueError(
            f"The parse of {title} gives an unknown {_INCLUDE_SIZE_ITEM} item"
        )
    return {"used": used, "limit": limit}


def _save(page, title, text, outcome, summary, live):
    guard = {}
    oldrevid = None
    if outcome == "update":
        if live is None:
            raise ValueError("An update needs the revision whose text it compared")
        oldrevid = live.revid
        # Pywikibot may fetch a newer revision while building its request. Keep both
        # guards tied to the revision whose text was compared.
        guard = {"baserevid": live.revid, "basetimestamp": live.timestamp}
    elif outcome != "create":
        raise ValueError(f"A save of a page whose outcome is {outcome!r}")
    page.text = text
    # Whatever pywikibot's configuration says, the text goes out exactly as generated,
    # as a bot edit: a creation onto a page that does not exist yet, or an update onto
    # the revision whose text was compared.
    page.save(
        summary,
        minor=False,
        bot=True,
        apply_cosmetic_changes=False,
        createonly=outcome == "create",
        nocreate=outcome == "update",
        **guard,
    )
    newrevid = page.latest_revision_id
    return {
        "title": title,
        "outcome": outcome,
        "pageid": page.pageid,
        "oldrevid": oldrevid,
        "newrevid": newrevid,
        "diff": he_diff_url(title, newrevid, "prev" if oldrevid is None else oldrevid),
        "verified": False,
    }


def _verify(saved, texts):
    """Read each saved revision through the API, uncached; mark it verified or fail."""
    failures = []
    with polite_download.PoliteDownloader(_CHECK_CONFIG) as downloader:
        client = ws_revision_api.ChapterClient(downloader, _API_PHP)
        for record in saved:
            identity = {
                "requested_title": record["title"],
                "resolved_title": record["title"],
                "page_id": record["pageid"],
                "revision_id": record["newrevid"],
            }
            try:
                content = _saved_content(client, identity)
            except ws_revision_api.ChapterResponseError as error:
                failures.append(
                    f"{record['title']}: no saved revision to read: {error}"
                )
                continue
            if content == texts[record["title"]].encode("utf-8"):
                record["verified"] = True
            else:
                failures.append(
                    f"{record['title']}: the saved text is not the text sent"
                )
    return failures


def _saved_content(client, identity):
    """The saved revision's bytes, waiting out a replica that has not yet seen it."""
    for wait_s in _REREAD_WAITS_S:
        try:
            _identity, revision = client.by_raw_revisions([identity])[
                identity["requested_title"]
            ]
            return revision["content"]
        except ws_revision_api.ChapterResponseError:
            if wait_s is None:
                raise
            time.sleep(wait_s)
    raise AssertionError("unreachable")


def _exit_if_any(outcomes, failures, no_save):
    lines = [f"- {line}" for line in failures]
    for entry in outcomes:
        if entry["outcome"] == "refuse":
            lines.append(f"- refused, {entry['reason']}: {entry['title']}")
            lines.extend(
                f"    revision {revision['revid']} by {revision['user'] or '(hidden)'}"
                f" at {revision['timestamp']}"
                for revision in entry["revisions"]
            )
        if entry["missing-pages"]:
            lines.append(f"- missing pages on {entry['title']}:")
            lines.extend(f"    {missing}" for missing in entry["missing-pages"])
        size = entry["include-size"]
        if size and 100 * size["used"] > _INCLUDE_SIZE_MAX_PERCENT * size["limit"]:
            lines.append(
                f"- more than {_INCLUDE_SIZE_MAX_PERCENT}% of the limit on the"
                f" post-expand include size, {size['used']} of {size['limit']} bytes:"
                f" {entry['title']}"
            )
    if no_save:
        lines.extend(
            f"- would {entry['outcome']}: {entry['title']}"
            for entry in outcomes
            if entry["outcome"] in ("create", "update")
        )
    if lines:
        raise SystemExit(
            "miqra-mevoar-display run found pages to report:\n" + "\n".join(lines)
        )


def _write_text_file(run_root, sub_dir, key, text):
    path = os.path.join(run_root, sub_dir, f"{key}.wiki")
    my_utils_fm.show_progress_g(__file__, path)
    file_io.with_tmp_openw(path, {}, _write_text, text)


def _write_text(text, outfp):
    outfp.write(text)


_RUNS_ROOT = ".novc/mam-ws-bot-miqra-mevoar-display-runs"
_STAMP = "%Y%m%d-%H%M%S-%f%z"
# The reason for refusing a page of PAGES, which exists with a text that differs from
# its generated text in more than a block at the top and the category line.
_ANOTHER_TEXT = (
    "a page that differs from its generated text in more than its block and its"
    " category line"
)
_INCLUDE_SIZE_ITEM = "limitreport-postexpandincludesize"
# By Ben's decision 12a of 2026-11-23, decisions ledger entry 21 of
# doc/PLAN-miqra-mevoar.md, a dry run fails a page that uses more than this percentage
# of its limit on the post-expand include size. Past the limit, MediaWiki leaves the
# page's last templates unexpanded, and the limit report gives the limit itself as
# the bytes used.
_INCLUDE_SIZE_MAX_PERCENT = 90
_API_PHP = "https://he.wikisource.org/w/api.php"
# The waits before each further read of a saved revision; None ends the reads.
_REREAD_WAITS_S = (5.0, 10.0, 20.0, None)
_CHECK_CONFIG = polite_download.PoliteDownloadConfig(
    user_agent="MAM-basics Miqra Mevoar bot check (https://github.com/bdenckla/MAM-basics)",
    throttle=polite_download.ThrottleConfig(min_delay_s=1.5),
)
