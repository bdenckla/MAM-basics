"""Create Miqra Mevoar's display pages on Hebrew Wikisource through the bot account.

Usage (run from the repository root):
    .venv/Scripts/python.exe py/main_ws_bot.py miqra-mevoar-display --no-save -dir:path/to/.pywikibot
    .venv/Scripts/python.exe py/main_ws_bot.py miqra-mevoar-display --summary "..." -dir:path/to/.pywikibot

Each selected page, every page of py/miqra_mevoar/display_page.py's PAGES unless --page
names some, is generated by display_page.page_text from MAM-simple and the tracked JSON
in in/miqra-mevoar/, and compared with the live page. The page then has one of three
outcomes:
  create     the page does not exist. It is saved with createonly, so that a page someone
             else made in the meantime is not overwritten.
  unchanged  the live text equals the generated text. Nothing is done.
  refuse     the page exists with another text. Nothing is saved for it; the run lists
             the editors of its revisions and exits non-zero when it ends. The mode never
             edits a page that exists: people, not the bot, reconcile such a page.

Every run writes each generated page to its pages/ directory and each page's outcome,
with its counts of verse lines, breaks and headings, to misc/outcomes.json. `--no-save`
also renders each generated page through the API's parse action, which saves nothing,
and requires that no link or transcluded page on it be missing, as a misspelled book
name or a missing base chapter would make one. It saves nothing and, like the other
modes' dry runs, exits non-zero if any page would be created. A saving run reads each
saved revision back through the API, uncached, requires its bytes to equal the generated
text's, records each page's new revision id and its diff link in misc/saved-pages.json,
and exits non-zero on any mismatch. No MAM page changes, so there is no post-run
download. Each run's artifacts go to a fresh directory under
.novc/mam-ws-bot-miqra-mevoar-display-runs/.
"""

import os
import time
from datetime import datetime

import pywikibot

from mb_cmn import file_io
from mb_cmn import polite_download
from mb_cmn.he_wikisource_url import he_diff_url
from mb_cmn.new_york_time import NEW_YORK
from mb_misc import my_utils_for_mainish as my_utils_fm
from miqra_mevoar import display_page
from subcommands import ws_bot_real
from ws import ws_revision_api


def run(keys, pywikibot_args, summary=None, no_save=False):
    """Create the selected display pages, saving nothing if no_save."""
    ws_bot_real.assert_pywikibot_dir_configured(pywikibot_args)
    if not no_save and not summary:
        raise SystemExit("A saving run needs --summary")
    selected = _selected_pages(keys)
    # Every page is generated, and its generator's checks pass, before any page is read.
    texts = {page.title(): display_page.page_text(page) for page in selected}
    run_root = os.path.join(_RUNS_ROOT, datetime.now(NEW_YORK).strftime(_STAMP))
    my_utils_fm.show_progress_g(__file__, "run-artifacts", run_root)
    site = pywikibot.Site("he", "wikisource", "BDencklaBot")
    outcomes, saved, failures = [], [], []
    try:
        for page_entry in selected:
            title = page_entry.title()
            _write_text_file(run_root, page_entry.key, texts[title])
            page = pywikibot.Page(site, title)
            outcome, revisions = _outcome(page, texts[title])
            verses, _name = display_page.read_page(texts[title])
            entry = {
                "key": page_entry.key,
                "title": title,
                "outcome": outcome,
                "revisions": revisions,
                "counts": _counts(verses),
                "missing-pages": None,
            }
            outcomes.append(entry)
            print(f"{outcome:<9} {title}")
            if no_save:
                entry["missing-pages"] = _missing_pages(site, title, texts[title])
                continue
            if outcome != "create":
                continue
            try:
                saved.append(_save(page, title, texts[title], summary))
            except pywikibot.exceptions.Error as error:
                failures.append(f"{title}: the save failed: {error!r}")
                break
    finally:
        file_io.json_dump_to_file_path(
            outcomes, os.path.join(run_root, "misc", "outcomes.json")
        )
        if saved:
            failures.extend(_verify(saved, texts))
        file_io.json_dump_to_file_path(
            saved, os.path.join(run_root, "misc", "saved-pages.json")
        )
    _exit_if_any(outcomes, failures, no_save)


def _selected_pages(keys):
    """The pages that --page names, in the order named, or every page in PAGES."""
    if not keys:
        return list(display_page.PAGES.values())
    if len(set(keys)) != len(keys):
        raise SystemExit(f"A --page is given twice: {keys}")
    if unknown := sorted(set(keys) - set(display_page.PAGES)):
        raise SystemExit(
            f"No --page {unknown}; the pages are {list(display_page.PAGES)}"
        )
    return [display_page.PAGES[key] for key in keys]


def _outcome(page, text):
    """The page's outcome and, for a refusal, the editors of its revisions."""
    if not page.exists():
        return "create", []
    if page.text == text:
        return "unchanged", []
    return "refuse", [
        {
            "revid": revision.revid,
            "user": revision.user,
            "timestamp": revision.timestamp.isoformat(),
        }
        for revision in page.revisions()
    ]


def _counts(verses):
    """A page's counts, in the columns of Stage 10's table in doc/PLAN-miqra-mevoar.md."""
    breaks = sum(verse.letter is not None for verse in verses)
    headings = sum(verse.heading is not None for verse in verses)
    both = sum(
        verse.letter is not None and verse.heading is not None for verse in verses
    )
    return {
        "verse-lines": len(verses),
        "petuhot": sum(verse.letter == display_page.PE for verse in verses),
        "setumot": sum(verse.letter == display_page.SAMEKH for verse in verses),
        "headings": headings,
        "break-only": breaks - both,
        "heading-only": headings - both,
        "both": both,
    }


def _missing_pages(site, title, text):
    """The links and transcluded pages of text, rendered as title, that do not exist."""
    parsed = site.simple_request(
        action="parse",
        title=title,
        text=text,
        contentmodel="wikitext",
        prop="links|templates",
        formatversion=2,
    ).submit()["parse"]
    missing = []
    for prop in ("links", "templates"):
        for item in parsed[prop]:
            if not isinstance(item.get("exists"), bool) or "title" not in item:
                raise ValueError(f"The parse of {title} gives an unknown {prop} item")
            if not item["exists"]:
                missing.append(item["title"])
    return sorted(set(missing))


def _save(page, title, text, summary):
    page.text = text
    # Whatever pywikibot's configuration says, the text goes out exactly as generated,
    # onto a page that does not exist yet, as a bot edit.
    page.save(
        summary,
        minor=False,
        bot=True,
        apply_cosmetic_changes=False,
        createonly=True,
    )
    newrevid = page.latest_revision_id
    return {
        "title": title,
        "outcome": "create",
        "pageid": page.pageid,
        "oldrevid": None,
        "newrevid": newrevid,
        "diff": he_diff_url(title, newrevid, "prev"),
        "verified": False,
    }


def _verify(saved, texts):
    """Read each saved revision through the API, uncached; mark it verified or fail."""
    failures = []
    with polite_download.PoliteDownloader(_CHECK_CONFIG) as downloader:
        client = ws_revision_api.ChapterClient(downloader, _API_PHP)
        for record in saved:
            identity = {
                "requested_title": record["title"],
                "resolved_title": record["title"],
                "page_id": record["pageid"],
                "revision_id": record["newrevid"],
            }
            try:
                content = _saved_content(client, identity)
            except ws_revision_api.ChapterResponseError as error:
                failures.append(
                    f"{record['title']}: no saved revision to read: {error}"
                )
                continue
            if content == texts[record["title"]].encode("utf-8"):
                record["verified"] = True
            else:
                failures.append(
                    f"{record['title']}: the saved text is not the text sent"
                )
    return failures


def _saved_content(client, identity):
    """The saved revision's bytes, waiting out a replica that has not yet seen it."""
    for wait_s in _REREAD_WAITS_S:
        try:
            _identity, revision = client.by_raw_revisions([identity])[
                identity["requested_title"]
            ]
            return revision["content"]
        except ws_revision_api.ChapterResponseError:
            if wait_s is None:
                raise
            time.sleep(wait_s)
    raise AssertionError("unreachable")


def _exit_if_any(outcomes, failures, no_save):
    lines = [f"- {line}" for line in failures]
    for entry in outcomes:
        if entry["outcome"] == "refuse":
            lines.append(f"- refused, a page with another text: {entry['title']}")
            lines.extend(
                f"    revision {revision['revid']} by {revision['user'] or '(hidden)'}"
                f" at {revision['timestamp']}"
                for revision in entry["revisions"]
            )
        if entry["missing-pages"]:
            lines.append(f"- missing pages on {entry['title']}:")
            lines.extend(f"    {missing}" for missing in entry["missing-pages"])
    if no_save:
        lines.extend(
            f"- would create: {entry['title']}"
            for entry in outcomes
            if entry["outcome"] == "create"
        )
    if lines:
        raise SystemExit(
            "miqra-mevoar-display run found pages to report:\n" + "\n".join(lines)
        )


def _write_text_file(run_root, key, text):
    path = os.path.join(run_root, "pages", f"{key}.wiki")
    my_utils_fm.show_progress_g(__file__, path)
    file_io.with_tmp_openw(path, {}, _write_text, text)


def _write_text(text, outfp):
    outfp.write(text)


_RUNS_ROOT = ".novc/mam-ws-bot-miqra-mevoar-display-runs"
_STAMP = "%Y%m%d-%H%M%S-%f%z"
_API_PHP = "https://he.wikisource.org/w/api.php"
# The waits before each further read of a saved revision; None ends the reads.
_REREAD_WAITS_S = (5.0, 10.0, 20.0, None)
_CHECK_CONFIG = polite_download.PoliteDownloadConfig(
    user_agent="MAM-basics Miqra Mevoar bot check (https://github.com/bdenckla/MAM-basics)",
    throttle=polite_download.ThrottleConfig(min_delay_s=1.5),
)
